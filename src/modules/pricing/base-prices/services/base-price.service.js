import api from '@/services/api'

const BasePriceService = {
  /*
  |--------------------------------------------------------------------------
  | LIST
  |--------------------------------------------------------------------------
  */

  getAll(params = {}) {
    return api.get('/pricing/base-prices', {
      params,
    })
  },

  /*
  |--------------------------------------------------------------------------
  | SHOW
  |--------------------------------------------------------------------------
  */

  get(id) {
    return api.get(`/pricing/base-prices/${id}`)
  },

  /*
  |--------------------------------------------------------------------------
  | CREATE
  |--------------------------------------------------------------------------
  */

  create(data) {
    return api.post('/pricing/base-prices', data)
  },

  /*
  |--------------------------------------------------------------------------
  | UPDATE
  |--------------------------------------------------------------------------
  */

  update(id, data) {
    return api.put(`/pricing/base-prices/${id}`, data)
  },

  /*
  |--------------------------------------------------------------------------
  | DELETE
  |--------------------------------------------------------------------------
  */

  delete(id) {
    return api.delete(`/pricing/base-prices/${id}`)
  },
}

export default BasePriceService
